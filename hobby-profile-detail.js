function profileHobbyDetailWeight(item, P) {
  const [, base, o = {}] = item;
  let w = base || 1;
  const a = P.age;
  if (o.m && P.sex === 'm') w *= o.m;
  if (o.f && P.sex === 'f') w *= o.f;
  if (o.young && a < 30) w *= o.young;
  if (o.mid && a >= 30 && a < 60) w *= o.mid;
  if (o.old && a >= 60) w *= o.old;
  if (o.metro && P.urb === 'metro') w *= o.metro;
  if (o.rural && (P.urb === 'rural' || P.urb === 'mid')) w *= o.rural;
  if (o.coast && P.pref?.coast) w *= o.coast;
  if (o.tags && o.tags.includes(P.occ?.tag)) w *= 1.45;
  return w;
}

function assignProfileHobbyDetails(P) {
  if (!P?.hobbies?.length) return;
  P.hobbies.forEach(h => {
    if (h.detail) return;
    const pool = PROFILE_HOBBY_DETAILS[h.i];
    if (!pool?.length) {
      h.detail = PROFILE_HOBBY_SHORT[h.i];
      h.detailP = 1;
      return;
    }
    const r = pickW(pool, x => profileHobbyDetailWeight(x, P));
    h.detail = r ? r.v[0] : PROFILE_HOBBY_SHORT[h.i];
    h.detailP = r?.p || 1;
  });
}

const PROFILE_ASSIGN_PROFILES_BASE = assignProfiles;
assignProfiles = function(P) {
  PROFILE_ASSIGN_PROFILES_BASE(P);
  if (P?.age >= 3 && P.age < 10) assignProfileChildHobby(P);
  else assignProfileHobbyDetails(P);
};

const PROFILE_HOBBY_LABEL_BASE = profileHobbyLabel;
profileHobbyLabel = function(P) {
  if (!P || P.age < 3) return '-';
  if (P.profileDisplay?.hobby) return P.profileDisplay.hobby;
  if (P.age < 10) {
    assignProfileChildHobby(P);
    return P.childHobby || '-';
  }
  if (P.hobbies?.length) {
    assignProfileHobbyDetails(P);
    const labels = P.hobbies.map(h => h.detail || PROFILE_HOBBY_SHORT[h.i]);
    return [...new Set(labels)].join('、');
  }
  return P.hobbyNote || PROFILE_HOBBY_LABEL_BASE(P);
};

